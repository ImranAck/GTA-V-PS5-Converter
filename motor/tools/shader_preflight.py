#!/usr/bin/env python3
"""Early *read-only* shader coverage check. Never guesses shader substitutions.

Uses exactly the same verified native reference corpus and schema extraction as
convert_pc_vehicle.py; the mod's own material report is already generated by the
upstream pipeline. The check avoids expensive model assembly when the target
corpus cannot represent the source shader. Additional templates need new audited
sources, not just changed hash allowlists.
"""
import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

HERE=Path(__file__).resolve().parent
if str(HERE) not in sys.path:sys.path.insert(0,str(HERE))
import gen9_materials
import convert_pc_vehicle as cv
import user_shader_library
from gtavmenu_tools import vehicle_contracts, drawable_contracts, vehicle_templates
from gtavmenu_tools.asset_formats import AssetError, decode_resource


def native_types(templates: Path)->set[int]:
    native=templates/'corpus/tornado6.pft'
    accepted=vehicle_templates.geometry_observation(native)
    contract=accepted['freshFragmentEvidence']['contract']
    base=contract['rootPlacement']['sourceBase']
    off=contract['rootPlacement']['sourceOffset']+contract['link']['drawableOffset']
    mat=vehicle_contracts.load()['native']['material']
    shader=drawable_contracts.load()['shader']
    refs=[];supp=set()
    args=type('ReferenceArgs',(),{'shader_reference':None})()
    for path,raw in cv.template_references(args,templates,native):
        identity=hashlib.sha256(raw).hexdigest()
        if not path.resolve().is_relative_to(templates.resolve()) or 'corpus/'+path.name in cv.REFERENCE_CACHES[3:]:supp.add(identity)
        if path.suffix.lower()=='.pdr':
            if path.resolve().is_relative_to(templates.resolve()):
                raise AssetError('PDR no autorizado como referencia primaria')
            checked, rows=user_shader_library.read_materials(path)
            if checked!=identity:raise AssetError('Referencia PDR modificada')
            refs.append((identity,rows))
            continue
        head,payload=decode_resource(raw,32*1024*1024)
        drawable=struct.unpack_from('<Q',payload,off)[0]-base
        slot=drawable+mat['drawableShaderGroupOffset']
        if drawable<0 or slot+8>head['systemBytes']:
            raise AssetError('Puntero de materiales fuera del recurso original')
        group=struct.unpack_from('<Q',payload,slot)[0]-base
        rows=gen9_materials.read_group(payload[:head['systemBytes']],base,group,shader)
        refs.append((identity,rows))
    return {int(k) for k in gen9_materials.schema_bank(refs,frozenset(supp))}


def report_types(report:Path)->set[int]:
    data=json.loads(report.read_text(encoding='utf-8'))
    return {int(sh['nameHash'],16) for row in data['resources'] for sh in row.get('shaders',[])}


def check(report:Path, templates:Path)->list[int]:
    return sorted(report_types(report)-native_types(templates))


def main(argv=None):
    p=argparse.ArgumentParser(description='Preflight de shaders originales PS5')
    p.add_argument('--report',type=Path,required=True)
    p.add_argument('--templates',type=Path,required=True)
    args=p.parse_args(argv)
    missing=check(args.report,args.templates)
    if missing:
        hashes=', '.join(f'0x{h:08x}' for h in missing)
        print('SHADER_PREFLIGHT=UNSUPPORTED '+hashes,flush=True)
        mappings=drawable_contracts.load()['shader']['mappings']
        print('SHADER_NAMES_MISSING='+', '.join(str(mappings.get(str(h), {}).get('name', 'desconocido')) for h in missing),flush=True)
        print('El corpus de shaders original no cubre esos tipos. No se sustituirán por otros arbitrariamente. Se evita la conversión 3D costosa.',flush=True)
        return 4
    print('SHADER_PREFLIGHT=PASS',flush=True)
    return 0

if __name__=='__main__':raise SystemExit(main())
